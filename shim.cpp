/** Play unsigned 8-bit PCM asynchronously on the V2 audio mixer. */
//%
void playPCMShim(Buffer samples, int sampleRate) {
    if (!samples || samples->length <= 0) return;
    player.play(samples->data, samples->length, sampleRate);
}

/** Native flash-backed 15 second test. */
//%
void playBadApple15sShim() {
    const int rate = 1000;
    const int totalSamples = 15000;
    const int chunkSamples = 250;
    uint8_t pcm[chunkSamples];
    int produced = 0;
    int packedIndex = 0;
    int bit = 7;

    while (produced < totalSamples) {
        int n = totalSamples - produced;
        if (n > chunkSamples) n = chunkSamples;
        for (int i = 0; i < n; ++i) {
            uint8_t x = badApple15Packed[packedIndex];
            pcm[i] = ((x >> bit) & 1) ? 224 : 32;
            if (--bit < 0) { bit = 7; ++packedIndex; }
        }
        player.play(pcm, n, rate);
        fiber_sleep(n);
        produced += n;
    }
}

//%
bool isPlayingShim() { return player.isPlaying(); }
//%
void stopShim() { player.stop(); }

